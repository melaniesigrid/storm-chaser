/**
 * Strips the fixed crescent out of the Meteocons night icons.
 *
 *   node scripts/build-night-icons.mjs
 *
 * Every Meteocons night glyph draws the same waning crescent, whatever the
 * moon is actually doing. The app already knows the real phase -- src/core/sky
 * computes it from solar and lunar longitudes and draws the true terminator --
 * so the icons were the one place still asserting a moon that is usually not
 * the one overhead.
 *
 * Overlaying the real moon on top of the crescent does not work: the unlit
 * side of a moon is very nearly transparent, so there is nothing to paint that
 * would hide the glyph underneath without also filling in the dark limb. The
 * crescent has to actually leave the file. That is what this does, writing the
 * remainder to src/core/icons/night/, where <NightIcon> renders it over a real
 * Moon.
 *
 * It is a build step with committed output rather than a runtime transform
 * because Metro compiles .svg imports into components at bundle time: there is
 * no SVG left to edit by the time the app is running.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'node_modules/@meteocons/svg-static/flat');
// Output lands beside the component that consumes it rather than in assets/,
// because there is no path alias for assets/ and `@/../assets/...` is not a
// thing anyone should have to read.
const out = resolve(root, 'src/core/icons/night');

/** The six shipped icons that contain a moon. */
const ICONS = [
  'clear-night',
  'starry-night',
  'partly-cloudy-night',
  'overcast-night',
  'fog-night',
  'thunderstorms-night-rain',
];

/**
 * Cut one balanced <g id="Moon"> ... </g> out of the markup.
 *
 * A regex cannot do this. The moon group nests further groups and paths, so
 * a non-greedy match to the first `</g>` truncates the file mid-element and a
 * greedy one swallows every sibling after it -- both of which render as a
 * blank icon and neither of which throws. Counting depth is the only honest
 * way.
 */
function cutMoon(svg) {
  const open = svg.indexOf('<g id="Moon"');
  if (open === -1) return null;

  let depth = 0;
  let i = open;

  while (i < svg.length) {
    const nextOpen = svg.indexOf('<g', i);
    const nextClose = svg.indexOf('</g>', i);
    if (nextClose === -1) return null;

    if (nextOpen !== -1 && nextOpen < nextClose) {
      depth += 1;
      i = nextOpen + 2;
    } else {
      depth -= 1;
      i = nextClose + 4;
      if (depth === 0) return svg.slice(0, open) + svg.slice(i);
    }
  }
  return null;
}

mkdirSync(out, { recursive: true });

let failures = 0;

for (const name of ICONS) {
  const svg = readFileSync(resolve(source, `${name}.svg`), 'utf8');
  const stripped = cutMoon(svg);

  if (stripped === null) {
    console.error(`${name}: no balanced <g id="Moon"> found`);
    failures += 1;
    continue;
  }

  // The guard that matters. A cut that removed too much leaves a file that
  // still parses and still renders -- as nothing. Comparing what came out
  // against what a moon group should weigh catches both directions.
  const removed = svg.length - stripped.length;
  if (removed < 80 || removed > svg.length * 0.9) {
    console.error(`${name}: cut ${removed} of ${svg.length} bytes, which is not a moon`);
    failures += 1;
    continue;
  }
  if (stripped.includes('id="Moon')) {
    console.error(`${name}: a moon is still in the output`);
    failures += 1;
    continue;
  }

  const header =
    '<!-- Generated by scripts/build-night-icons.mjs from @meteocons/svg-static.\n' +
    '     The moon is removed on purpose: src/core/icons/NightIcon.tsx draws the\n' +
    '     real phase behind this. Do not edit by hand. -->\n';

  writeFileSync(resolve(out, `${name}.svg`), header + stripped, 'utf8');
  console.log(`${name}: removed ${removed} bytes of crescent`);
}

/*
 * The landing page's copy of the same glyph.
 *
 * landing/ is plain HTML with no build step and no access to src/, so it keeps
 * its own icon files. It had the same fixed crescent, and a marketing page
 * showing a moon the product would not show is a small lie told at scale --
 * so it gets the same treatment, with the phase computed by a few lines of
 * inline script in index.html.
 */
const landing = resolve(root, 'landing/icons');
const landingSource = readFileSync(resolve(landing, 'starry-night.svg'), 'utf8');
const landingStripped = cutMoon(landingSource);

if (landingStripped === null || landingStripped.includes('id="Moon')) {
  console.error('landing/icons/starry-night.svg: no balanced moon group to remove');
  failures += 1;
} else {
  const landingHeader = `<!-- Generated by scripts/build-night-icons.mjs from starry-night.svg.
     The moon is removed on purpose: index.html draws the real phase over
     this. Do not edit by hand. -->
`;

  writeFileSync(
    resolve(landing, 'starry-night-moonless.svg'),
    landingHeader + landingStripped,
    'utf8',
  );
  console.log(
    `landing starry-night: removed ${landingSource.length - landingStripped.length} bytes of crescent`,
  );
}

if (failures > 0) process.exit(1);
